// Generates the OLED app logo: a dot-matrix "download" glyph (arrow into a
// tray) on pure black, unlit cells drawn faintly like the in-app dot-matrix
// readouts, and a single red dot at the arrow tip (the "live" colour).
//
// Run from the repo root:  dart run tool/generate_oled_logo.dart
//
// Outputs
//   assets/brand/logo.svg                    master artwork (1024)
//   assets/brand/logo-1024.png, logo-512.png store / marketing sizes
//   android/.../drawable/ic_launcher_foreground.xml   adaptive foreground
//   android/.../drawable/ic_launcher_monochrome.xml   themed icon (Android 13)
//   android/.../mipmap-*/ic_launcher.png      legacy launchers (API < 26)
import 'dart:io';
import 'dart:math' as math;

import 'package:image/image.dart' as img;

// Palette (OledTokens).
const _black = 0xFF000000;
const _ink = 0xFFF4F4F2;
const _unlit = 0xFF171717;
const _live = 0xFFFF4A3D;

/// Adaptive-icon canvas, in dp. The launcher mask keeps a 66 dp circle.
const double _canvas = 108;
const double _pitch = 6.5;
const double _dot = 2.35; // radius
const int _cols = 7;
const int _rows = 9;

enum _Cell { unlit, lit, live }

/// The glyph, top to bottom. `#` lit, `*` live, `.` unlit.
const List<String> _glyph = [
  '...#...',
  '...#...',
  '...#...',
  '#..#..#',
  '.#.#.#.',
  '..###..',
  '...*...',
  '.......',
  '.#####.',
];

class _Dot {
  const _Dot(this.x, this.y, this.cell);
  final double x;
  final double y;
  final _Cell cell;
}

/// Dots in canvas units. Unlit cells outside a 31 dp radius are dropped so
/// the field reads as a round display and stays inside the safe zone.
List<_Dot> _dots() {
  final dots = <_Dot>[];
  const cx = _canvas / 2;
  const cy = _canvas / 2;
  for (var r = 0; r < _rows; r++) {
    for (var c = 0; c < _cols; c++) {
      final x = cx + (c - (_cols - 1) / 2) * _pitch;
      final y = cy + (r - (_rows - 1) / 2) * _pitch;
      final ch = _glyph[r][c];
      final cell = ch == '#'
          ? _Cell.lit
          : ch == '*'
          ? _Cell.live
          : _Cell.unlit;
      final distance = math.sqrt(math.pow(x - cx, 2) + math.pow(y - cy, 2));
      if (cell == _Cell.unlit && distance > 31) continue;
      dots.add(_Dot(x, y, cell));
    }
  }
  return dots;
}

String _hex(int argb) =>
    '#${(argb & 0xFFFFFF).toRadixString(16).padLeft(6, '0').toUpperCase()}';

String _circlePath(double x, double y, double r) {
  String f(double v) => v.toStringAsFixed(2);
  return 'M${f(x - r)},${f(y)}a${f(r)},${f(r)} 0 1,0 ${f(2 * r)},0'
      'a${f(r)},${f(r)} 0 1,0 ${f(-2 * r)},0';
}

String _vector({required bool monochrome}) {
  final buf = StringBuffer()
    ..writeln('<?xml version="1.0" encoding="utf-8"?>')
    ..writeln('<!-- Generated by tool/generate_oled_logo.dart -->')
    ..writeln(
      '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
    )
    ..writeln('    android:width="108dp"')
    ..writeln('    android:height="108dp"')
    ..writeln('    android:viewportWidth="108"')
    ..writeln('    android:viewportHeight="108">');
  for (final cell in _Cell.values) {
    if (monochrome && cell == _Cell.unlit) continue;
    final paths = _dots()
        .where((d) => d.cell == cell)
        .map((d) => _circlePath(d.x, d.y, _dot))
        .join();
    final color = monochrome
        ? '#FFFFFFFF'
        : switch (cell) {
            _Cell.unlit => _hex(_unlit),
            _Cell.lit => _hex(_ink),
            _Cell.live => _hex(_live),
          };
    buf
      ..writeln('    <path')
      ..writeln('        android:fillColor="$color"')
      ..writeln('        android:pathData="$paths" />');
  }
  buf.writeln('</vector>');
  return buf.toString();
}

/// Master SVG: black rounded square, glyph scaled from the 72 dp visible
/// area of the adaptive canvas to fill 1024.
String _svg() {
  const size = 1024.0;
  const visible = 80.0; // a little air around the glyph
  const scale = size / visible;
  const offset = (_canvas - visible) / 2;
  final buf = StringBuffer()
    ..writeln(
      '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" '
      'width="1024" height="1024">',
    )
    ..writeln('  <title>Modern Downloader</title>')
    ..writeln(
      '  <rect width="1024" height="1024" rx="224" fill="${_hex(_black)}"/>',
    );
  for (final d in _dots()) {
    final color = switch (d.cell) {
      _Cell.unlit => _hex(_unlit),
      _Cell.lit => _hex(_ink),
      _Cell.live => _hex(_live),
    };
    buf.writeln(
      '  <circle cx="${((d.x - offset) * scale).toStringAsFixed(1)}" '
      'cy="${((d.y - offset) * scale).toStringAsFixed(1)}" '
      'r="${(_dot * scale).toStringAsFixed(1)}" fill="$color"/>',
    );
  }
  buf.writeln('</svg>');
  return buf.toString();
}

/// Raster of the visible 72 dp area on a black rounded square, rendered at
/// 4x and downsampled for clean edges.
img.Image _raster(int size, {double cornerRatio = 0.22}) {
  const ss = 4;
  final big = size * ss;
  final canvas = img.Image(width: big, height: big, numChannels: 4);
  img.fill(canvas, color: img.ColorRgba8(0, 0, 0, 0));
  final radius = (big * cornerRatio).round();
  img.fillRect(
    canvas,
    x1: 0,
    y1: 0,
    x2: big - 1,
    y2: big - 1,
    radius: radius,
    color: _color(_black),
  );
  const visible = 80.0;
  const offset = (_canvas - visible) / 2;
  final scale = big / visible;
  for (final d in _dots()) {
    img.fillCircle(
      canvas,
      x: ((d.x - offset) * scale).round(),
      y: ((d.y - offset) * scale).round(),
      radius: (_dot * scale).round(),
      color: _color(switch (d.cell) {
        _Cell.unlit => _unlit,
        _Cell.lit => _ink,
        _Cell.live => _live,
      }),
      antialias: true,
    );
  }
  return img.copyResize(
    canvas,
    width: size,
    height: size,
    interpolation: img.Interpolation.average,
  );
}

img.Color _color(int argb) => img.ColorRgba8(
  (argb >> 16) & 0xFF,
  (argb >> 8) & 0xFF,
  argb & 0xFF,
  (argb >> 24) & 0xFF,
);

Future<void> main() async {
  const res = 'android/app/src/main/res';
  Future<void> write(String path, Object data) async {
    final file = File(path);
    await file.parent.create(recursive: true);
    if (data is String) {
      await file.writeAsString(data);
    } else {
      await file.writeAsBytes(data as List<int>);
    }
    stdout.writeln('wrote $path');
  }

  await write('assets/brand/logo.svg', _svg());
  await write('assets/brand/logo-1024.png', img.encodePng(_raster(1024)));
  await write('assets/brand/logo-512.png', img.encodePng(_raster(512)));
  await write(
    '$res/drawable/ic_launcher_foreground.xml',
    _vector(monochrome: false),
  );
  await write(
    '$res/drawable/ic_launcher_monochrome.xml',
    _vector(monochrome: true),
  );
  const legacy = {
    'mdpi': 48,
    'hdpi': 72,
    'xhdpi': 96,
    'xxhdpi': 144,
    'xxxhdpi': 192,
  };
  for (final entry in legacy.entries) {
    await write(
      '$res/mipmap-${entry.key}/ic_launcher.png',
      img.encodePng(_raster(entry.value)),
    );
  }
}
